import yaml
import argparse
from pathlib import Path

from rfdetr.assets.coco_classes import COCO_CLASSES

def export_coco_classes(output_path: str):
    file_path = Path(output_path) / "coco_classes.yaml"

    if file_path.is_file():
        raise RuntimeError(f"The file at {file_path} already exists. Delete or move the existing file before exporting.")

    with open(file_path, "w") as file:
        file.write("# Generated by models/export_rfdetr_pretrained_classes.py from rfdetr's COCO_CLASSES.\n"
        "# Keys are COCO category IDs, which match the logit slot indices.\n")
        yaml.dump(COCO_CLASSES, file, sort_keys=False)


if __name__ == "__main__":
    default_output_path = Path(__file__).parent.parent.resolve() /"config"
    parser = argparse.ArgumentParser(description="Export the pretrained COCO RF-DETR classes to a designated directory as YAML.")
    parser.add_argument("-d", "--directory", type=str, default=str(default_output_path), help="The directory to export the COCO class file to.")

    args = parser.parse_args()
    export_coco_classes(args.directory)